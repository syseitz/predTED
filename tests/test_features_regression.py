# ---------------------------------------------------------------------------
# Regression tests (one per structure)
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("structure", STRUCTURES)
def test_feature_regression(structure: str) -> None:
    """Assert that compute_features returns the pre-refactoring baseline."""
    expected = np.array(EXPECTED_FEATURES[structure], dtype=np.float64)
    actual = compute_features(structure)
    np.testing.assert_allclose(
        actual,
        expected,
        rtol=1e-10,
        atol=1e-12,
        err_msg=f"Feature regression failure for structure: '{structure}'",
    )


# ---------------------------------------------------------------------------
# Capture helper (run this file directly to regenerate EXPECTED_FEATURES)
# ---------------------------------------------------------------------------

def capture_baseline() -> None:
    """Print EXPECTED_FEATURES dict with current compute_features output."""
    print("EXPECTED_FEATURES: dict[str, list[float]] = {")
    for structure in STRUCTURES:
        features = compute_features(structure).tolist()
        print(f"    {structure!r}: {features!r},")
    print("}")


if __name__ == "__main__":
    capture_baseline()
